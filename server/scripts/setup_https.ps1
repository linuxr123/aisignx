# Install Caddy and generate deploy\Caddyfile for HTTPS in front of AISignX.
# Run from server/:  powershell -ExecutionPolicy Bypass -File scripts\setup_https.ps1
#
#   -Hostname signage.example.com
#   -Email admin@example.com          # optional, for Let's Encrypt account
#   -InstallService                   # register Windows service (needs Admin)
#   -NonInteractive                   # skip prompts; try winget + portable download

param(
    [string]$Hostname = $env:AISIGNX_HOSTNAME,
    [string]$Email = $env:AISIGNX_EMAIL,
    [switch]$InstallService,
    [switch]$NonInteractive
)

$ErrorActionPreference = 'Stop'
$ServerDir = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$DeployDir = Join-Path $ServerDir 'deploy'
$Caddyfile = Join-Path $DeployDir 'Caddyfile'
$ToolsDir = Join-Path $ServerDir 'tools\caddy'
$PortableCaddy = Join-Path $ToolsDir 'caddy.exe'
$WingetPackageId = 'CaddyServer.Caddy'

if (-not $Hostname) {
    $Hostname = $env:COMPUTERNAME
    if (-not $Hostname) { $Hostname = 'localhost' }
}

function Test-InternalTls {
    param([string]$Name)
    if ($Name -match '^(localhost|127\.0\.0\.1|::1)$') { return $true }
    if ($Name -like '*.local') { return $true }
    if ($Name -match '^\d{1,3}(\.\d{1,3}){3}$') { return $true }
    return $false
}

function Write-Caddyfile {
    $internal = Test-InternalTls $Hostname
    New-Item -ItemType Directory -Force -Path $DeployDir | Out-Null
    $stamp = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
    if ($internal) {
        Write-Host '[!] Using Caddy internal TLS (browser warning once; not a public CA).' -ForegroundColor Yellow
        @"
# Generated by setup_https.ps1 - $stamp
$Hostname {
    tls internal
    reverse_proxy 127.0.0.1:5000
}
"@ | Set-Content -Path $Caddyfile -Encoding UTF8
    } else {
        Write-Host "[OK] Automatic Let's Encrypt for $Hostname" -ForegroundColor Green
        Write-Host '[!] DNS must point here; ports 80 and 443 open.' -ForegroundColor Yellow
        if ($Email) {
            @"
# Generated by setup_https.ps1 - $stamp
{
    email $Email
}

$Hostname {
    reverse_proxy 127.0.0.1:5000
}
"@ | Set-Content -Path $Caddyfile -Encoding UTF8
        } else {
            @"
# Generated by setup_https.ps1 - $stamp
$Hostname {
    reverse_proxy 127.0.0.1:5000
}
"@ | Set-Content -Path $Caddyfile -Encoding UTF8
        }
    }
    Write-Host "[OK] Wrote $Caddyfile" -ForegroundColor Green
}

function Refresh-SessionPath {
    $machine = [System.Environment]::GetEnvironmentVariable('Path', 'Machine')
    $user = [System.Environment]::GetEnvironmentVariable('Path', 'User')
    $env:Path = "$machine;$user"
}

function Find-CaddyExe {
    Refresh-SessionPath
    $cmd = Get-Command caddy -ErrorAction SilentlyContinue
    if ($cmd -and $cmd.Source) { return $cmd.Source }

    $candidates = @(
        $PortableCaddy,
        'C:\Program Files\Caddy\caddy.exe',
        "$env:ProgramFiles\Caddy\caddy.exe",
        "$env:LOCALAPPDATA\Microsoft\WinGet\Links\caddy.exe",
        "$env:LOCALAPPDATA\Microsoft\WinGet\Packages\Caddy.Caddy_*\caddy.exe"
    )
    foreach ($pattern in $candidates) {
        $resolved = @(Get-Item -Path $pattern -ErrorAction SilentlyContinue)
        if ($resolved.Count -gt 0) { return $resolved[0].FullName }
    }
    $wingetGlob = Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Packages'
    if (Test-Path $wingetGlob) {
        $found = Get-ChildItem -Path $wingetGlob -Filter 'caddy.exe' -Recurse -ErrorAction SilentlyContinue |
            Select-Object -First 1
        if ($found) { return $found.FullName }
    }
    return $null
}

function Get-CaddyWindowsZipUrl {
    try {
        $release = Invoke-RestMethod -Uri 'https://api.github.com/repos/caddyserver/caddy/releases/latest' -UseBasicParsing
        $asset = $release.assets | Where-Object {
            $_.name -match '^caddy_.*_windows_amd64\.zip$' -and $_.name -notmatch 'debug'
        } | Select-Object -First 1
        if ($asset.browser_download_url) {
            Write-Host "[*] Caddy release: $($release.tag_name) ($($asset.name))" -ForegroundColor Gray
            return $asset.browser_download_url
        }
    } catch {
        Write-Host "[!] GitHub API lookup failed: $($_.Exception.Message)" -ForegroundColor Yellow
    }
    throw 'Could not resolve Caddy Windows download URL from GitHub.'
}

function Install-CaddyPortable {
    Write-Host '[*] Downloading portable Caddy to tools\caddy\ ...' -ForegroundColor Yellow
    $zipUrl = Get-CaddyWindowsZipUrl
    New-Item -ItemType Directory -Force -Path $ToolsDir | Out-Null
    $zipPath = Join-Path $env:TEMP "caddy_windows_amd64_$([Guid]::NewGuid().ToString('N')).zip"
    try {
        Invoke-WebRequest -Uri $zipUrl -OutFile $zipPath -UseBasicParsing
        Expand-Archive -Path $zipPath -DestinationPath $ToolsDir -Force
        if (-not (Test-Path $PortableCaddy)) {
            $exe = Get-ChildItem -Path $ToolsDir -Filter 'caddy.exe' -Recurse -ErrorAction SilentlyContinue |
                Select-Object -First 1
            if ($exe) {
                Copy-Item -Path $exe.FullName -Destination $PortableCaddy -Force
            }
        }
    } finally {
        Remove-Item -Path $zipPath -Force -ErrorAction SilentlyContinue
    }
    if (-not (Test-Path $PortableCaddy)) {
        throw "Portable download failed. Get Caddy from https://caddyserver.com/download"
    }
    Write-Host "[OK] Portable Caddy: $PortableCaddy" -ForegroundColor Green
    return $PortableCaddy
}

function Ensure-Caddy {
    $existing = Find-CaddyExe
    if ($existing) {
        Write-Host "[OK] Caddy: $existing" -ForegroundColor Green
        & $existing version 2>&1 | Select-Object -First 1
        return $existing
    }

    if (Get-Command winget -ErrorAction SilentlyContinue) {
        Write-Host '[*] Installing Caddy via winget (may need a new terminal if PATH is stale)...' -ForegroundColor Yellow
        try {
            winget install --id $WingetPackageId -e --accept-source-agreements --accept-package-agreements 2>&1 | Out-Host
        } catch {
            Write-Host '[!] winget install did not complete cleanly; trying portable download.' -ForegroundColor Yellow
        }
        $existing = Find-CaddyExe
        if ($existing) {
            Write-Host "[OK] Caddy: $existing" -ForegroundColor Green
            return $existing
        }
    }

    return Install-CaddyPortable
}

function Note-StartScripts {
    Write-Host '[OK] Start: .\scripts\start_server.ps1' -ForegroundColor Green
}

Write-Host ''
Write-Host 'AISignX HTTPS setup (Caddy)' -ForegroundColor Cyan
Write-Host ''
Write-Caddyfile

$internal = Test-InternalTls $Hostname
$caddyExe = $null
if ($NonInteractive) {
    try { $caddyExe = Ensure-Caddy } catch {
        Write-Host "[!] $($_.Exception.Message)" -ForegroundColor Yellow
        Write-Host '[!] Install Caddy manually, then run deploy\Caddyfile.' -ForegroundColor Yellow
    }
} else {
    $ans = Read-Host 'Install Caddy now if missing? [Y/n]'
    if ($ans -notmatch '^[Nn]') {
        try { $caddyExe = Ensure-Caddy } catch {
            Write-Host "[FAIL] $($_.Exception.Message)" -ForegroundColor Red
        }
    }
}

if (-not $caddyExe) { $caddyExe = Find-CaddyExe }
Note-StartScripts

if ($InstallService) {
    if (-not $caddyExe) { $caddyExe = Ensure-Caddy }
    & $caddyExe stop 2>$null
    & $caddyExe uninstall 2>$null
    & $caddyExe install --config $Caddyfile
    & $caddyExe start
    Write-Host "[OK] Caddy Windows service started (https://$Hostname/)" -ForegroundColor Green
} else {
    Write-Host ''
    Write-Host 'Next steps:' -ForegroundColor Green
    Write-Host "  One command (from $ServerDir):"
    Write-Host "     .\scripts\start_server.ps1 -Hostname $Hostname"
    Write-Host "  Stop:       .\scripts\stop_server.ps1"
    Write-Host "  Restart:    .\scripts\restart_server.ps1 -Hostname $Hostname"
    Write-Host "  Admin UI: https://$Hostname/"
    if ($internal) {
        Write-Host '  For a trusted cert (no browser warning), use a public DNS name instead of an IP.'
    }
    Write-Host ''
    Write-Host 'Service install (Admin): .\scripts\setup_https.ps1 -Hostname ... -InstallService' -ForegroundColor Gray
}
